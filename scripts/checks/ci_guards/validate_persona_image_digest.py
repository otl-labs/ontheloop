"""The persona image name and digest live in one file (T4.2 c13 second half; T4.32 c2).

config/persona_image.yaml is the only tracked file (besides docs/plans/**, which describe the image) that may hold an
image reference. This check also keeps the image's build honest: a digest-pinned base, COPY sources and build-context
allow-list equal to the pin's build.copy plus the lock, built consumers that read the pin, pending consumers owned by
an open roadmap criterion, and Dependabot watching the image's lock and base. It never compares the image lock with
requirements-dev.txt: the lock is the image's own and the conformance suite tests each bump. Two further rules (rec-5383)
keep the image on the repository's Python line: Dependabot ignores the base image's semver-major and semver-minor
updates (never a patch, versions or full ignore, so same-tag digest refreshes still arrive), and the Dockerfile base
tag's MAJOR.MINOR, the lock header's pip-compile Python and the repository's .python-version must be equal. The lock
stays the image's own, but its Python line now follows .python-version.

Decision 170: calls registry.examined() on every reachable exit path.
"""

from __future__ import annotations

import ast
import fnmatch
import re
import subprocess
from pathlib import Path
from typing import Any

import yaml

from scripts.checks import _common, registry
from src.persona_hosts.image_pin import ImagePin, load_pin

_PREFIX = "persona-image-digest"
_LOCK = "docker/persona/requirements-persona.txt"
_ROADMAP = "docs/ROADMAP-PLATFORM.yaml"
_DEPENDABOT = ".github/dependabot.yml"
_FROM_DIGEST = re.compile(r"^FROM\s+\S+@sha256:[0-9a-f]{64}(\s|$)", re.M)
_COPY = re.compile(r"^COPY\s+(?:--\S+\s+)*(\S+)\s+(\S+)\s*$", re.M)
_PYTHON_VERSION = ".python-version"
_FROM_LINE = re.compile(r"^\s*FROM\s+(.+)$", re.I | re.M)
_LOCK_PYTHON = re.compile(r"autogenerated by pip-compile with Python (\d+\.\d+)", re.I)
_MAJOR_MINOR = re.compile(r"\s*(\d+\.\d+)")
_IGN = "python-ignore"
_LINE = "python-line"
_NO_BASE = "cannot determine the base image from the Dockerfile (need exactly one FROM with a name and tag)"
_RULE_COUNT = 8


def _reference_hits(root: Path, pin: ImagePin) -> list[str]:
    proc = subprocess.run(
        ["git", "grep", "-n", "-I", "-F", "-e", f"{pin.image}:", "-e", f"{pin.image}@", "--",
         ".", ":(exclude)config/persona_image.yaml", ":(exclude)docs/plans"],
        cwd=root, capture_output=True, text=True, encoding="utf-8", errors="replace",
    )  # fmt: skip
    if proc.returncode not in (0, 1):
        return [f"git grep for the image reference failed: {proc.stderr.strip()[:200]}"]
    return [
        f"{line.split(':', 2)[0]}: holds an image reference; read it through load_pin" for line in proc.stdout.splitlines()
    ]


def _calls_load_pin(path: Path) -> bool:
    for py in [path] if path.is_file() else sorted(path.rglob("*.py")):
        try:
            tree = ast.parse(py.read_text(encoding="utf-8"))
        except (OSError, SyntaxError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                fn = node.func
                if (isinstance(fn, ast.Name) and fn.id == "load_pin") or (
                    isinstance(fn, ast.Attribute) and fn.attr == "load_pin"
                ):
                    return True
    return False


def _open_criterion(root: Path, owning_item: str) -> bool:
    item_id, _, crit = owning_item.partition(":")
    try:
        data = yaml.safe_load((root / _ROADMAP).read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return False
    for item in data.get("tier_items", []):
        if item.get("id") == item_id:
            return any(c.get("id") == crit and c.get("status") == "open" for c in item.get("exit_criteria") or [])
    return False


def _consumer_findings(root: Path, pin: ImagePin) -> list[str]:
    out: list[str] = []
    for name, row in pin.consumers:
        if row["status"] == "built":
            location = root / row["location"]
            if not location.exists():
                out.append(f"consumer {name}: location {row['location']} does not exist")
            elif not _calls_load_pin(location):
                out.append(f"consumer {name}: no .py file under {row['location']} calls load_pin")
        elif not _open_criterion(root, row["owning_item"]):
            out.append(f"consumer {name}: owning_item {row['owning_item']} is not an open roadmap criterion")
    return out


def _dockerfile_findings(root: Path, pin: ImagePin) -> list[str]:
    out: list[str] = []
    dockerfile = root / pin.dockerfile
    try:
        text = dockerfile.read_text(encoding="utf-8")
    except OSError:
        return [f"{pin.dockerfile} is unreadable"]
    if not _FROM_DIGEST.search(text):
        out.append(f"{pin.dockerfile}: FROM is not pinned by digest")
    expected = set(pin.copy) | {_LOCK}
    copied = {m.group(1) for m in _COPY.finditer(text)}
    if copied != expected:
        out += [
            f"{pin.dockerfile}: COPY of {p} is not in build.copy; add it to config/persona_image.yaml"
            for p in sorted(copied - expected)
        ]
        out += [f"{pin.dockerfile}: build.copy line {p} is never copied" for p in sorted(expected - copied)]
    ignore = root / f"{pin.dockerfile}.dockerignore"
    try:
        lines = [ln.strip() for ln in ignore.read_text(encoding="utf-8").splitlines()]
    except OSError:
        return [*out, f"{ignore.relative_to(root)} is unreadable"]
    allowed = {ln[1:] for ln in lines if ln.startswith("!")}
    if allowed != expected:
        out += [f"{ignore.name}: allow-list lacks {p}; add !{p}" for p in sorted(expected - allowed)]
        out += [f"{ignore.name}: allow-list holds {p}, which is not a build.copy line" for p in sorted(allowed - expected)]
    return out


def _base_image(root: Path, pin: ImagePin) -> tuple[str, str] | None:
    try:
        text = (root / pin.dockerfile).read_text(encoding="utf-8")
    except OSError:
        return None
    froms = _FROM_LINE.findall(text)
    if len(froms) != 1:
        return None
    tokens = froms[0].split()
    while tokens and tokens[0].startswith("--"):
        tokens.pop(0)
    if not tokens or "$" in tokens[0]:
        return None
    ref = tokens[0].split("@", 1)[0]
    colon = ref.rfind(":")
    if colon <= ref.rfind("/") or colon == 0:
        return None
    return ref[:colon], ref[colon + 1 :]


def _ignore_findings(entry: dict[str, Any], name: str) -> list[str]:
    ignore = entry.get("ignore")
    if ignore is None:
        return [f"{_IGN}: docker entry has no ignore row for {name}"]
    if not isinstance(ignore, list):
        return [f"{_IGN}: ignore is not a list"]
    out: list[str] = []
    satisfied = False
    for row in ignore:
        if not isinstance(row, dict):
            out.append(f"{_IGN}: an ignore row is not a mapping")
            continue
        dep = row.get("dependency-name")
        if not isinstance(dep, str) or not fnmatch.fnmatchcase(name, dep):
            continue
        types = row.get("update-types")
        if types is not None and not isinstance(types, list):
            out.append(f"{_IGN}: update-types of the {dep} row is not a list")
            continue
        if "versions" in row:
            out.append(f"{_IGN}: the {dep} row holds a versions key; digest refreshes are not proven to pass it")
        if not types and "versions" not in row:
            out.append(f"{_IGN}: the {dep} row ignores every update, which stops digest refreshes")
        elif "version-update:semver-patch" in (types or []):
            out.append(f"{_IGN}: the {dep} row holds semver-patch; patch and digest refreshes must still arrive")
        if dep == name and {"version-update:semver-major", "version-update:semver-minor"} <= set(types or []):
            satisfied = True
    if not satisfied:
        out.append(f"{_IGN}: no ignore row named {name} holds both semver-major and semver-minor")
    return out


def _dependabot_findings(root: Path, pin: ImagePin) -> list[str]:
    directory = "/" + Path(pin.dockerfile).parent.as_posix()
    try:
        config: Any = yaml.safe_load((root / _DEPENDABOT).read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return [f"{_DEPENDABOT} is unreadable"]
    updates = [u for u in (config or {}).get("updates", []) if isinstance(u, dict)]
    have = {(u.get("package-ecosystem"), u.get("directory")) for u in updates}
    out = [f"{_DEPENDABOT}: no {eco} update for {directory}" for eco in ("pip", "docker") if (eco, directory) not in have]
    entry = next((u for u in updates if (u.get("package-ecosystem"), u.get("directory")) == ("docker", directory)), None)
    if entry is not None:
        base = _base_image(root, pin)
        out += [f"{_IGN}: {_NO_BASE}"] if base is None else _ignore_findings(entry, base[0])
    return out


def _python_line_findings(root: Path, pin: ImagePin) -> list[str]:
    base = _base_image(root, pin)
    if base is None:
        return [f"{_LINE}: {_NO_BASE}"]
    out: list[str] = []
    values: dict[str, str] = {}
    tag = _MAJOR_MINOR.match(base[1])
    if tag:
        values[f"{pin.dockerfile} base tag"] = tag.group(1)
    else:
        out.append(f"{_LINE}: base tag {base[1]} has no MAJOR.MINOR")
    for label, rel, find in (
        (f"{_LOCK} header", _LOCK, _LOCK_PYTHON.search),
        (_PYTHON_VERSION, _PYTHON_VERSION, _MAJOR_MINOR.match),
    ):
        try:
            match = find((root / rel).read_text(encoding="utf-8"))
        except OSError:
            out.append(f"{_LINE}: {rel} is unreadable")
            continue
        if match:
            values[label] = match.group(1)
        else:
            out.append(f"{_LINE}: {rel} holds no readable Python version")
    if not out and len(set(values.values())) > 1:
        out.append(f"{_LINE}: Python lines disagree: " + ", ".join(f"{k} = {v}" for k, v in values.items()))
    return out


@registry.register("validate_persona_image_digest", owner="platform")
def validate_persona_image_digest(failed: list[str]) -> None:
    """One image file, a digest-pinned base, and a build that matches the pin. See module docstring."""
    print("\n=== persona image digest guard ===")
    root = _common.ROOT
    try:
        pin = load_pin(root)
    except ValueError as exc:
        print(f"  FAIL: {exc}")
        failed.append(f"{_PREFIX}: {exc}")
        registry.examined(1, unit="image_pin_rules")
        return
    found = [
        *_reference_hits(root, pin),
        *_consumer_findings(root, pin),
        *_dockerfile_findings(root, pin),
        *_dependabot_findings(root, pin),
        *_python_line_findings(root, pin),
    ]
    for line in found:
        print(f"  FAIL: {line}")
        failed.append(f"{_PREFIX}: {line}")
    if not found:
        print("  PASS: the image pin, Dockerfile, build context, Dependabot and the Python line agree")
    registry.examined(_RULE_COUNT, unit="image_pin_rules")
